function findFiles(dir, ext) {
  const results = [];
  try {
    const items = fs.readdirSync(dir, { withFileTypes: true });
    for (const item of items) {
      const full = path.join(dir, item.name);
      if (item.isDirectory()) results.push(...findFiles(full, ext));
      else if (item.name.endsWith(ext)) results.push(full);
    }
  } catch {}
  return results;
}

const root = path.join(__dirname, '..');
const files = [
  ...findFiles(path.join(root, 'src', 'app'), '.tsx'),
  ...findFiles(path.join(root, 'src', 'app'), '.ts'),
  ...findFiles(path.join(root, 'src', 'components'), '.tsx'),
  ...findFiles(path.join(root, 'src', 'components'), '.ts'),
];

let totalFixed = 0;

for (const file of files) {
  let content = fs.readFileSync(file, 'utf8');
  const original = content;

  // Replace `lang !== 'en' ? 'arabicText' : 'englishText'` with proper 3-way
  // Pattern: lang !== 'en' ? 'XXX' : 'YYY'
  content = content.replace(/lang !== 'en' \? '([^']+)' : '([^']+)'/g, (match, ar, en) => {
    const ur = arToUr[ar] || ar; // fallback to Arabic if no Urdu translation
    if (ur === ar) return match; // no change if same
    return `lang === 'en' ? '${en}' : lang === 'ur' ? '${ur}' : '${ar}'`;
  });

  // Also handle template literals: lang !== 'en' ? `XXX` : `YYY`
  content = content.replace(/lang !== 'en' \? `([^`]+)` : `([^`]+)`/g, (match, ar, en) => {
    const ur = arToUr[ar] || ar;
    if (ur === ar) return match;
    return `lang === 'en' ? \`${en}\` : lang === 'ur' ? \`${ur}\` : \`${ar}\``;
  });

  if (content !== original) {
    fs.writeFileSync(file, content, 'utf8');
    const changes = content.split("lang === 'ur'").length - original.split("lang === 'ur'").length;
    if (changes > 0) {
      console.log(`${path.relative(root, file)}: ${changes} Urdu inline texts added`);
      totalFixed += changes;
    }
  }
}

console.log(`\nTotal: ${totalFixed} inline texts now have proper Urdu`);
